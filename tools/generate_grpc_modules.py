"""Renders the per-RPC gnoi_* / gnsi_* modules from tools/nokia_grpc_modules.yaml.

Usage:
  python tools/generate_grpc_modules.py           write plugins/modules, remove stale gnoi_/gnsi_ modules
  python tools/generate_grpc_modules.py --check   exit 1 if any module differs from the manifest
"""

import argparse
import re
import sys
import textwrap
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / 'tools' / 'nokia_grpc_modules.yaml'
MODULE_DIR = ROOT / 'plugins' / 'modules'
# ansible-test pep8 allows 160 characters
LINE_WIDTH = 140
# stream is the generated gNSI stream option; Ansible core reserves the others
RESERVED_OPTIONS = ('stream', 'message', 'syslog_facility')

PROTOCOLS = ('gnoi', 'gnsi')
PATTERNS = ('unary', 'server_streaming', 'client_streaming', 'bidi_streaming')
PLATFORMS = {'sros': 'SR OS', 'srl': 'SR Linux'}
VALIDATION = ('unit', 'integration')
ENCODINGS = ('path', 'paths', 'duration')
ENTRY_KEYS = {'module', 'protocol', 'service', 'rpc', 'pattern', 'platforms', 'validation', 'read_only',
              'short_description', 'description', 'notes', 'options', 'returns', 'examples', 'stream_message'}
DOC_OPTION_KEYS = ('description', 'type', 'required', 'default', 'choices', 'elements')
SPEC_OPTION_KEYS = ('field', 'encode', 'transport')

HEADER = '''#!/usr/bin/python
# (c) 2026 Nokia
#
# Licensed under the BSD 3 Clause license
# SPDX-License-Identifier: BSD-3-Clause
#
# Generated by tools/generate_grpc_modules.py from tools/nokia_grpc_modules.yaml.
# Edit the manifest and regenerate; changes to this file are overwritten.

from __future__ import absolute_import, division, print_function
__metaclass__ = type
'''


class ManifestError(ValueError):
    pass


def snake(name):
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).lower()


def load_manifest(path=MANIFEST):
    with open(path) as handle:
        entries = yaml.safe_load(handle)['modules']
    seen = set()
    for entry in entries:
        validate_entry(entry)
        if entry['module'] in seen:
            raise ManifestError('duplicate module %s' % entry['module'])
        seen.add(entry['module'])
    return entries


def validate_entry(entry):
    name = entry.get('module', '?')

    def fail(msg):
        raise ManifestError('%s: %s' % (name, msg))

    unknown = set(entry) - ENTRY_KEYS
    if unknown:
        fail('unknown keys %s' % sorted(unknown))
    if entry['protocol'] not in PROTOCOLS:
        fail('protocol must be one of %s' % (PROTOCOLS,))
    expected = '%s_%s_%s' % (entry['protocol'], entry['service'], snake(entry['rpc']))
    if name != expected:
        fail('module must be named %s' % expected)
    if entry['pattern'] not in PATTERNS:
        fail('pattern must be one of %s' % (PATTERNS,))
    if not entry['platforms'] or set(entry['platforms']) - set(PLATFORMS):
        fail('platforms must be a non-empty subset of %s' % sorted(PLATFORMS))
    if 'unit' not in entry['validation'] or set(entry['validation']) - set(VALIDATION):
        fail('validation must include unit and only use %s' % (VALIDATION,))
    if not isinstance(entry['read_only'], bool):
        fail('read_only must be a bool')
    if is_stream(entry) != bool(entry.get('stream_message')):
        fail('stream_message is required exactly for gNSI bidi_streaming RPCs')
    for opt, spec in (entry.get('options') or {}).items():
        unknown = set(spec) - set(DOC_OPTION_KEYS) - set(SPEC_OPTION_KEYS)
        if unknown:
            fail('option %s: unknown keys %s' % (opt, sorted(unknown)))
        if ('field' in spec) == ('transport' in spec):
            fail('option %s needs exactly one of field or transport' % opt)
        if spec.get('encode') not in (None,) + ENCODINGS:
            fail('option %s: encode must be one of %s' % (opt, ENCODINGS))
        if opt in RESERVED_OPTIONS:
            fail('option name %s is reserved' % opt)


def is_stream(entry):
    return entry['protocol'] == 'gnsi' and entry['pattern'] == 'bidi_streaming'


# --- DOCUMENTATION -----------------------------------------------------------

def scalar(value):
    """Renders a YAML scalar, quoting only when plain style would change it."""
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    text = str(value)
    try:
        plain = yaml.safe_load('k: %s' % text) == {'k': text}
    except yaml.YAMLError:
        plain = False
    if plain and not text.startswith(('"', "'")):
        return text
    return '"%s"' % text.replace('\\', '\\\\').replace('"', '\\"')


def as_list(value):
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def list_item(indent, value):
    """Renders one YAML list item, folding long plain scalars to stay under the sanity line limit."""
    text = scalar(value)
    single = ['%s- %s' % (indent, text)]
    if len(single[0]) <= LINE_WIDTH:
        return single
    wrapped = textwrap.wrap(text, width=LINE_WIDTH, initial_indent=indent + '- ',
                            subsequent_indent=indent + '  ', break_long_words=False, break_on_hyphens=False)
    try:
        folded = yaml.safe_load('\n'.join(wrapped))
    except yaml.YAMLError:
        folded = None
    if folded != [value]:
        return single
    return wrapped


def list_items(indent, values):
    return [line for value in as_list(values) for line in list_item(indent, value)]


def platform_note(entry):
    names = ' and '.join(PLATFORMS[p] for p in ('sros', 'srl') if p in entry['platforms'])
    note = 'Supported on Nokia %s.' % names
    if entry['protocol'] == 'gnsi':
        note += ' gNSI must be enabled on the gRPC server.'
    elif entry['platforms'] == ['sros']:
        note += ' SR Linux does not implement this RPC.'
    return note


FINALIZE = {'credentialz': 'finalize'}


def pattern_note(entry):
    pattern = entry['pattern']
    if pattern == 'server_streaming':
        return ('Server-streaming RPC. The task sends one request and collects every response message until '
                'the device ends the stream, then returns them in RV(output). The task fails if the stream '
                'does not end within the command timeout of the connection (C(ansible_command_timeout)).')
    if pattern == 'client_streaming':
        return ('Client-streaming RPC. The task streams O(local_path) in 64 KiB chunks followed by its SHA-256 '
                'hash, then returns the single response of the device. The upload must complete within the '
                'command timeout of the connection (C(ansible_command_timeout)).')
    if pattern == 'bidi_streaming' and is_stream(entry):
        finalize = FINALIZE.get(entry['service'], 'finalizeRotation')
        return ('Bidirectional streaming RPC with a request sequence defined by the playbook. The O(stream) '
                'messages are sent in the given order without waiting for responses, and every server message '
                'is collected until the device closes the stream. The task cannot react to intermediate '
                'responses, so a rotation that needs data from the device within the same stream, such as '
                'signing a CSR generated by the device, is not possible. The device rolls back the rotation '
                'if the stream closes without a finalize message, so end O(stream) with C(%s).' % finalize)
    if pattern == 'bidi_streaming':
        return ('Bidirectional streaming RPC. The connection sends the request sequence built from the options '
                'and collects every server message until the device closes the stream.')
    return None


def notes(entry):
    result = ['Requires P(nokia.openconfig.grpc#connection).', platform_note(entry)]
    result.extend(as_list(entry.get('notes')))
    if entry['read_only']:
        result.append('Read-only RPC. Runs in check mode and always reports C(changed=false).')
    else:
        result.append('Reports C(changed=true). In check mode the RPC is not sent and the task is skipped.')
    note = pattern_note(entry)
    if note:
        result.append(note)
    if 'integration' not in entry['validation']:
        result.append('Not exercised by the collection integration tests on Nokia devices; '
                      'covered by unit tests against the gNOI/gNSI mock server.')
    return result


def doc_options(entry):
    options = dict(entry.get('options') or {})
    if is_stream(entry):
        options['stream'] = {
            'description': ['Client messages in send order. Each item holds the protobuf JSON fields of one '
                            'C(%s).' % entry['stream_message']],
            'type': 'list',
            'elements': 'dict',
            'required': True,
        }
    return options


def render_documentation(entry):
    lines = ['---', 'module: %s' % entry['module'], 'author:', '  - "Sven Wisotzky (@wisotzky)"',
             'short_description: %s' % scalar(entry['short_description']), 'description:']
    lines += list_items('  ', entry['description'])
    lines.append('version_added: 2.0.0')
    options = doc_options(entry)
    if options:
        lines.append('options:')
        for opt, spec in options.items():
            lines.append('  %s:' % opt)
            lines.append('    description:')
            lines += list_items('      ', spec['description'])
            lines.append('    type: %s' % spec['type'])
            if spec.get('elements'):
                lines.append('    elements: %s' % spec['elements'])
            if spec.get('required'):
                lines.append('    required: true')
            if 'default' in spec:
                lines.append('    default: %s' % scalar(spec['default']))
            if spec.get('choices'):
                lines.append('    choices:')
                lines += ['      - %s' % scalar(c) for c in spec['choices']]
    else:
        lines.append('options: {}')
    lines.append('notes:')
    lines += list_items('  ', notes(entry))
    lines += ['requirements:', '  - grpcio', '  - protobuf']
    return '\n'.join(lines)


def render_return(entry):
    if entry['pattern'] in ('server_streaming', 'bidi_streaming'):
        desc = 'Response messages as a JSON list in stream order (protobuf JSON names).'
    else:
        desc = 'Response message as JSON (protobuf JSON names).'
    returns = {'output': {'description': desc, 'type': 'str', 'returned': 'success'}}
    returns.update(entry.get('returns') or {})
    lines = []
    for key, spec in returns.items():
        lines += ['%s:' % key, '  description: %s' % scalar(spec['description']),
                  '  type: %s' % spec['type'], '  returned: %s' % scalar(spec['returned'])]
    return '\n'.join(lines)


# --- Python ------------------------------------------------------------------

def py_dict(name, mapping, indent):
    pad = ' ' * indent
    if not mapping:
        return []
    lines = ['%s%s={' % (pad, name)]
    lines += ['%s    %r: %r,' % (pad, k, v) for k, v in mapping.items()]
    lines.append('%s},' % pad)
    return lines


def argument_spec(entry):
    lines = []
    for opt, spec in doc_options(entry).items():
        parts = ["type=%r" % spec['type']]
        if spec.get('required'):
            parts.append('required=True')
        if 'default' in spec:
            parts.append('default=%r' % spec['default'])
        if spec.get('choices'):
            parts.append('choices=%r' % list(spec['choices']))
        if spec.get('elements'):
            parts.append('elements=%r' % spec['elements'])
        line = '            %s=dict(%s),' % (opt, ', '.join(parts))
        if len(line) > 120 and spec.get('choices'):
            lines.append('            %s=dict(' % opt)
            lines += ['                %s,' % p for p in parts if not p.startswith('choices=')]
            lines.append('                choices=[')
            lines += ['                    %r,' % c for c in spec['choices']]
            lines.append('                ],')
            lines.append('            ),')
        else:
            lines.append(line)
    return lines


def rpc_spec(entry):
    options = entry.get('options') or {}
    fields = {o: s['field'] for o, s in options.items() if 'field' in s}
    encode = {o: s['encode'] for o, s in options.items() if s.get('encode')}
    transport = {o: s['transport'] for o, s in options.items() if 'transport' in s}
    lines = ['RPC = dict(', '    service=%r,' % entry['service'], '    rpc=%r,' % entry['rpc'],
             '    read_only=%r,' % entry['read_only']]
    lines += py_dict('fields', fields, 4)
    lines += py_dict('encode', encode, 4)
    lines += py_dict('transport', transport, 4)
    if is_stream(entry):
        lines.append('    stream=True,')
    lines.append(')')
    return lines


def render_module(entry):
    spec = argument_spec(entry)
    if spec:
        arg_lines = ['        argument_spec=dict(', *spec, '        ),']
    else:
        arg_lines = ['        argument_spec=dict(),']
    body = [
        HEADER,
        'DOCUMENTATION = """',
        render_documentation(entry),
        '"""',
        '',
        'EXAMPLES = """',
        entry['examples'].rstrip('\n'),
        '"""',
        '',
        'RETURN = """',
        render_return(entry),
        '"""',
        '',
        'from ansible.module_utils.basic import AnsibleModule',
        'from ansible_collections.nokia.openconfig.plugins.module_utils.%s_module import run' % entry['protocol'],
        '',
        *rpc_spec(entry),
        '',
        '',
        'def main():',
        '    module = AnsibleModule(',
        *arg_lines,
        '        supports_check_mode=True,',
        '    )',
        '    run(module, **RPC)',
        '',
        '',
        "if __name__ == '__main__':",
        '    main()',
        '',
    ]
    return '\n'.join(body)


def render_all(entries=None):
    entries = load_manifest() if entries is None else entries
    rendered = {}
    for entry in entries:
        content = render_module(entry)
        doc = yaml.safe_load(content.split('DOCUMENTATION = """', 1)[1].split('"""', 1)[0])
        if doc['module'] != entry['module']:
            raise ManifestError('%s: DOCUMENTATION does not round-trip' % entry['module'])
        rendered['%s.py' % entry['module']] = content
    return rendered


def stale_modules(rendered):
    existing = {p.name for p in MODULE_DIR.glob('gnoi_*.py')} | {p.name for p in MODULE_DIR.glob('gnsi_*.py')}
    return sorted(existing - set(rendered))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='only report modules that are out of date')
    args = parser.parse_args()

    rendered = render_all()
    outdated = [n for n, c in rendered.items()
                if not (MODULE_DIR / n).exists() or (MODULE_DIR / n).read_text() != c]
    stale = stale_modules(rendered)

    if args.check:
        for name in outdated:
            print('out of date: plugins/modules/%s' % name)
        for name in stale:
            print('not in manifest: plugins/modules/%s' % name)
        return 1 if outdated or stale else 0

    for name in outdated:
        (MODULE_DIR / name).write_text(rendered[name])
        print('wrote plugins/modules/%s' % name)
    for name in stale:
        (MODULE_DIR / name).unlink()
        print('removed plugins/modules/%s' % name)
    print('%d modules from %s' % (len(rendered), MANIFEST.relative_to(ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
